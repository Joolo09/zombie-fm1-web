"""Original deterministic synthetic GM percussion. No upstream audio assets.
Run from any directory; only Python's standard library is required.
"""
import math
from pathlib import Path
RATE = 22050
# name, GM notes, fundamental, duration, noise fraction
KIT = [
 ('kick',[35,36],52,.42,.03),('rim',[37],810,.09,.1),
 ('snare',[38,40],185,.28,.8),('clap',[39],1050,.22,.95),
 ('closed hat',[42,44],6200,.1,.95),('open hat',[46],5800,.48,.9),
 ('low tom',list(range(41,46)),110,.38,.04),('high tom',[47,48,50],180,.32,.04),
 ('crash',[49,52,55,57],3100,.65,.8),('ride',[51,53,59],2700,.6,.35),
 ('tambourine',[54],4800,.25,.8),('cowbell',[56],650,.3,.02),
 ('conga',[62,63,64],260,.3,.04),('shaker',[69,70,82],7200,.12,.96),
 ('claves',[75],2100,.08,.01),('woodblock',[76,77],1450,.12,.01)]
# Standard IMA ADPCM step table and index adjustment, not audio data.
STEPS = [7,8,9,10,11,12,13,14,16,17,19,21,23,25,28,31,34,37,41,45,50,55,60,66,73,80,88,97,107,118,130,143,157,173,190,209,230,253,279,307,337,371,408,449,494,544,598,658,724,796,876,963,1060,1166,1282,1411,1552,1707,1878,2066,2272,2499,2749,3024,3327,3660,4026,4428,4871,5358,5894,6484,7132,7845,8630,9493,10442,11487,12635,13899,15289,16818,18500,20350,22385,24623,27086,29794,32767]
ADJ = [-1,-1,-1,-1,2,4,6,8]
def encode(samples):
 pred=idx=0; codes=[]
 for value in samples:
  step=STEPS[idx];diff=value-pred;code=8 if diff<0 else 0;diff=abs(diff);delta=step>>3
  for bit,part in [(4,step),(2,step>>1),(1,step>>2)]:
   if diff>=part:code|=bit;diff-=part;delta+=part
  pred=max(-32768,min(32767,pred+(-delta if code&8 else delta)))
  idx=max(0,min(88,idx+ADJ[code&7]));codes.append(code)
 if len(codes)%2:codes.append(0)
 return bytes(codes[i]|codes[i+1]<<4 for i in range(0,len(codes),2))
def main():
 blob=bytearray();zones=[];seed=0x5a17
 used=set()
 for name,notes,freq,seconds,noise in KIT:
  samples=[];phase=0.;n=int(seconds*RATE)
  for i in range(n):
   t=i/RATE;seed=(1664525*seed+1013904223)&0xffffffff
   rnd=(seed>>8)/8388608.-1
   sweep=1+(.7*math.exp(-t*40) if name=='kick' else .12*math.exp(-t*30))
   phase+=2*math.pi*freq*sweep/RATE
   tone=math.sin(phase)*.8+math.sin(phase*1.471)*.2
   env=math.exp(-6*t/seconds)*min(1,i/12)
   samples.append(int(24000*env*((1-noise)*tone+noise*rnd)))
  off=len(blob);blob.extend(encode(samples))
  for note in notes:
   if note in used:continue
   used.add(note);zones.append((off,n,n,n,32768,note*16,0,0,note,note,0))
 lines=['/* SPDX-License-Identifier: CC0-1.0; generated by ../gen_samples.py */','#pragma once','#include <stdint.h>',f'static const uint8_t SMP_DATA[{len(blob)}] = {{']
 for at in range(0,len(blob),32):lines.append(','.join(map(str,blob[at:at+32]))+',')
 lines+=['};','static const smp_zone_t SMP_ZONES[] = {']
 lines += ['{'+','.join(map(str,z))+'},' for z in zones]
 lines+=['};',f'static const smp_set_t SMP_SETS[] = {{{{"ZOMBIE",0,{len(zones)}}}}};','#define SMP_NSETS 1','#define SMP_SET_NAMES_INIT "ZOMBIE"','static const char *const SMP_SET_NAMES[] = {"ZOMBIE"};','#define SLC_BREAK_INIT {0}']
 Path(__file__).with_name('gen').joinpath('felucca_samples.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
 print(f'Original Zombie kit: {len(zones)} zones, {len(blob)} ADPCM bytes')
if __name__=='__main__':main()
